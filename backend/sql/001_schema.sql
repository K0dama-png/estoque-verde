-- Execute conectado ao schema definido em ORACLE_USER.

CREATE TABLE markets (
  id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  name        VARCHAR2(150 CHAR) NOT NULL,
  document    VARCHAR2(14 CHAR) NOT NULL,
  city        VARCHAR2(100 CHAR) NOT NULL,
  active      NUMBER(1) DEFAULT 1 NOT NULL,
  created_at  TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at  TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_markets PRIMARY KEY (id),
  CONSTRAINT uq_markets_document UNIQUE (document),
  CONSTRAINT ck_markets_active CHECK (active IN (0, 1))
);

CREATE TABLE app_users (
  id                    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  market_id             NUMBER NOT NULL,
  name                  VARCHAR2(120 CHAR) NOT NULL,
  username              VARCHAR2(50 CHAR) NOT NULL,
  password_hash         VARCHAR2(255 CHAR) NOT NULL,
  role                  VARCHAR2(20 CHAR) NOT NULL,
  active                NUMBER(1) DEFAULT 1 NOT NULL,
  must_change_password  NUMBER(1) DEFAULT 0 NOT NULL,
  created_at            TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at            TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_app_users PRIMARY KEY (id),
  CONSTRAINT uq_app_users_id_market UNIQUE (id, market_id),
  CONSTRAINT fk_app_users_market FOREIGN KEY (market_id) REFERENCES markets (id),
  CONSTRAINT ck_app_users_role CHECK (role IN ('ADMIN', 'EMPLOYEE')),
  CONSTRAINT ck_app_users_active CHECK (active IN (0, 1)),
  CONSTRAINT ck_app_users_change_password CHECK (must_change_password IN (0, 1))
);

CREATE UNIQUE INDEX ux_app_users_username_ci ON app_users (LOWER(username));
CREATE INDEX ix_app_users_market ON app_users (market_id, active);

CREATE TABLE categories (
  id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  market_id   NUMBER NOT NULL,
  name        VARCHAR2(80 CHAR) NOT NULL,
  active      NUMBER(1) DEFAULT 1 NOT NULL,
  is_default  NUMBER(1) DEFAULT 0 NOT NULL,
  created_at  TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at  TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_categories PRIMARY KEY (id),
  CONSTRAINT uq_categories_id_market UNIQUE (id, market_id),
  CONSTRAINT fk_categories_market FOREIGN KEY (market_id) REFERENCES markets (id),
  CONSTRAINT ck_categories_active CHECK (active IN (0, 1)),
  CONSTRAINT ck_categories_default CHECK (is_default IN (0, 1))
);

CREATE UNIQUE INDEX ux_categories_market_name_ci ON categories (market_id, LOWER(name));
CREATE INDEX ix_categories_market ON categories (market_id, active);

CREATE TABLE suppliers (
  id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  market_id   NUMBER NOT NULL,
  name        VARCHAR2(150 CHAR) NOT NULL,
  document    VARCHAR2(14 CHAR) NOT NULL,
  phone       VARCHAR2(20 CHAR) NOT NULL,
  active      NUMBER(1) DEFAULT 1 NOT NULL,
  created_at  TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at  TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_suppliers PRIMARY KEY (id),
  CONSTRAINT uq_suppliers_id_market UNIQUE (id, market_id),
  CONSTRAINT uq_suppliers_document UNIQUE (market_id, document),
  CONSTRAINT fk_suppliers_market FOREIGN KEY (market_id) REFERENCES markets (id),
  CONSTRAINT ck_suppliers_active CHECK (active IN (0, 1))
);

CREATE INDEX ix_suppliers_market ON suppliers (market_id, active);

CREATE TABLE products (
  id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  market_id         NUMBER NOT NULL,
  category_id       NUMBER NOT NULL,
  code              VARCHAR2(50 CHAR) NOT NULL,
  name              VARCHAR2(150 CHAR) NOT NULL,
  description       VARCHAR2(500 CHAR),
  price             NUMBER(15, 2) DEFAULT 0 NOT NULL,
  current_quantity  NUMBER(15, 3) DEFAULT 0 NOT NULL,
  minimum_stock     NUMBER(15, 3) DEFAULT 0 NOT NULL,
  maximum_stock     NUMBER(15, 3) NOT NULL,
  unit              VARCHAR2(5 CHAR) NOT NULL,
  active            NUMBER(1) DEFAULT 1 NOT NULL,
  created_at        TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at        TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_products PRIMARY KEY (id),
  CONSTRAINT uq_products_id_market UNIQUE (id, market_id),
  CONSTRAINT fk_products_market FOREIGN KEY (market_id) REFERENCES markets (id),
  CONSTRAINT fk_products_category FOREIGN KEY (category_id, market_id)
    REFERENCES categories (id, market_id),
  CONSTRAINT ck_products_price CHECK (price >= 0),
  CONSTRAINT ck_products_quantity CHECK (current_quantity >= 0),
  CONSTRAINT ck_products_stock_limits CHECK (minimum_stock >= 0 AND maximum_stock >= minimum_stock),
  CONSTRAINT ck_products_unit CHECK (unit IN ('UN', 'KG', 'G', 'L', 'ML', 'CX', 'PCT')),
  CONSTRAINT ck_products_active CHECK (active IN (0, 1))
);

CREATE UNIQUE INDEX ux_products_market_code_ci ON products (market_id, UPPER(code));
CREATE INDEX ix_products_market_active ON products (market_id, active);
CREATE INDEX ix_products_category ON products (market_id, category_id);
CREATE INDEX ix_products_stock_alert ON products (market_id, current_quantity, minimum_stock);

CREATE TABLE batches (
  id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  market_id       NUMBER NOT NULL,
  product_id      NUMBER NOT NULL,
  supplier_id     NUMBER NOT NULL,
  code            VARCHAR2(60 CHAR) NOT NULL,
  quantity        NUMBER(15, 3) DEFAULT 0 NOT NULL,
  purchase_price  NUMBER(15, 4) DEFAULT 0 NOT NULL,
  expiry_date     DATE NOT NULL,
  received_at     TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  created_at      TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at      TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_batches PRIMARY KEY (id),
  CONSTRAINT uq_batches_id_market UNIQUE (id, market_id),
  CONSTRAINT fk_batches_market FOREIGN KEY (market_id) REFERENCES markets (id),
  CONSTRAINT fk_batches_product FOREIGN KEY (product_id, market_id)
    REFERENCES products (id, market_id),
  CONSTRAINT fk_batches_supplier FOREIGN KEY (supplier_id, market_id)
    REFERENCES suppliers (id, market_id),
  CONSTRAINT ck_batches_quantity CHECK (quantity >= 0),
  CONSTRAINT ck_batches_purchase_price CHECK (purchase_price >= 0)
);

CREATE UNIQUE INDEX ux_batches_product_code_ci ON batches (market_id, product_id, UPPER(code));
CREATE INDEX ix_batches_fefo ON batches (market_id, product_id, quantity, expiry_date, received_at);
CREATE INDEX ix_batches_expiry ON batches (market_id, expiry_date, quantity);

CREATE TABLE stock_movements (
  id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  market_id    NUMBER NOT NULL,
  type         VARCHAR2(10 CHAR) NOT NULL,
  exit_reason  VARCHAR2(20 CHAR),
  notes        VARCHAR2(500 CHAR),
  created_by   NUMBER NOT NULL,
  created_at   TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_stock_movements PRIMARY KEY (id),
  CONSTRAINT uq_movements_id_market UNIQUE (id, market_id),
  CONSTRAINT fk_movements_market FOREIGN KEY (market_id) REFERENCES markets (id),
  CONSTRAINT fk_movements_user FOREIGN KEY (created_by, market_id)
    REFERENCES app_users (id, market_id),
  CONSTRAINT ck_movements_type CHECK (type IN ('ENTRY', 'EXIT')),
  CONSTRAINT ck_movements_reason CHECK (
    (type = 'ENTRY' AND exit_reason IS NULL) OR
    (type = 'EXIT' AND exit_reason IN ('SALE', 'LOSS', 'EXPIRY', 'DAMAGE', 'INTERNAL_USE', 'ADJUSTMENT'))
  )
);

CREATE INDEX ix_movements_market_date ON stock_movements (market_id, created_at DESC);
CREATE INDEX ix_movements_user ON stock_movements (market_id, created_by);

CREATE TABLE stock_movement_items (
  id                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  movement_id          NUMBER NOT NULL,
  market_id            NUMBER NOT NULL,
  product_id           NUMBER NOT NULL,
  batch_id             NUMBER NOT NULL,
  supplier_id          NUMBER,
  quantity             NUMBER(15, 3) NOT NULL,
  unit_purchase_price  NUMBER(15, 4),
  CONSTRAINT pk_stock_movement_items PRIMARY KEY (id),
  CONSTRAINT fk_movement_items_movement FOREIGN KEY (movement_id, market_id)
    REFERENCES stock_movements (id, market_id),
  CONSTRAINT fk_movement_items_product FOREIGN KEY (product_id, market_id)
    REFERENCES products (id, market_id),
  CONSTRAINT fk_movement_items_batch FOREIGN KEY (batch_id, market_id)
    REFERENCES batches (id, market_id),
  CONSTRAINT fk_movement_items_supplier FOREIGN KEY (supplier_id, market_id)
    REFERENCES suppliers (id, market_id),
  CONSTRAINT ck_movement_items_quantity CHECK (quantity > 0),
  CONSTRAINT ck_movement_items_price CHECK (unit_purchase_price IS NULL OR unit_purchase_price >= 0)
);

CREATE INDEX ix_movement_items_movement ON stock_movement_items (market_id, movement_id);
CREATE INDEX ix_movement_items_product ON stock_movement_items (market_id, product_id);

COMMIT;
